using Microsoft.CodeAnalysis;

namespace KappaDuck.Khaos.Analyzers.Tests.Harness.Fixtures;

internal sealed class MemorySafetyGenerator : IIncrementalGenerator
{
    internal const string HintName = "MemorySafety.g.cs";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<bool> enabled = context.ParseOptionsProvider
            .Select(static (options, _) => options.Features.ContainsKey("updated-memory-safety-rules"));

        context.RegisterSourceOutput(enabled, static (output, on) => output.AddSource(HintName, $$"""
            // <auto-generated/>
            internal static class MemorySafety
            {
                public const bool Enabled = {{(on ? "true" : "false")}};
            }
            """));
    }
}
