using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace KappaDuck.Khaos.Analyzers.Tests.Harness.Fixtures;

internal sealed class SymbolGenerator : IIncrementalGenerator
{
    internal const string Symbols = nameof(Symbols);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<ISymbol?> symbols = context.SyntaxProvider
            .CreateSyntaxProvider(static (node, _) => node is ClassDeclarationSyntax, static (syntax, token) => syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, token))
            .WithTrackingName(Symbols);

        context.RegisterSourceOutput(symbols, static (output, symbol) => output.AddSource($"{symbol?.Name}.g.cs", "// <auto-generated/>"));
    }
}
