using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace KappaDuck.Khaos.Analyzers.Tests.Harness.Fixtures;

internal sealed class TypeNameGenerator : IIncrementalGenerator
{
    internal const string Names = nameof(Names);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<string> names = context.SyntaxProvider
            .CreateSyntaxProvider(static (node, _) => node is ClassDeclarationSyntax, static (syntax, _) => ((ClassDeclarationSyntax)syntax.Node).Identifier.ValueText)
            .WithTrackingName(Names);

        context.RegisterSourceOutput(names, static (output, name) => output.AddSource($"{name}.g.cs", $$"""
            // <auto-generated/>
            partial class {{name}}
            {
                public const string TypeName = "{{name}}";
            }

            """));
    }
}
