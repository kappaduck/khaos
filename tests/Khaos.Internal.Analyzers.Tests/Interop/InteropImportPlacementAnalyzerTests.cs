    [Test]
    public async Task LibraryImportOutsideInteropWithItsGeneratedHalfShouldReportKHI009Once()
    {
        const string declaration = """
            using System.Runtime.InteropServices;

            namespace KappaDuck.Khaos.Windowing;

            internal static partial class Native
            {
                [LibraryImport("SDL3", EntryPoint = "SDL_Quit")]
                internal static partial void Quit();
            }
            """;

        AnalyzerResult result = await AnalyzerRunner<InteropImportPlacementAnalyzer>.RunAsync(declaration, GeneratedQuit);

        await result.CompilationErrors.Should().BeEmpty();
        await result.Ids.Should().BeEqualTo("KHI009");
        await result.Reported.Should().Contain("Source0.cs(8,34)");
    }

    [Test]
    public async Task LibraryImportInTheSDLAndWin32AreasShouldReportNothing()
    {
        const string sdl = """
            using System.Runtime.InteropServices;

            namespace KappaDuck.Khaos.Interop.SDL;

            internal static partial class SDL3
            {
                [LibraryImport("SDL3", EntryPoint = "SDL_Quit")]
                internal static partial void Quit();
            }
            """;

        const string win32 = """
            using System.Runtime.InteropServices;

            namespace KappaDuck.Khaos.Interop.Win32;

            internal static partial class User32
            {
                [LibraryImport("user32", EntryPoint = "GetSystemMetrics")]
                internal static partial int GetSystemMetrics(int nIndex);
            }
            """;

        AnalyzerResult result = await AnalyzerRunner<InteropImportPlacementAnalyzer>.RunAsync(sdl, win32);

        await result.CompilationErrors.Should().BeEmpty();
        await result.Ids.Should().BeEmpty();
    }

    [Test]
    public async Task MethodWithoutLibraryImportOutsideInteropShouldReportNothing()
    {
        const string source = """
            namespace KappaDuck.Khaos.Windowing;

            internal static class Native
            {
                internal static void Quit()
                {
                }
            }
            """;

        AnalyzerResult result = await AnalyzerRunner<InteropImportPlacementAnalyzer>.RunAsync(source);

        await result.CompilationErrors.Should().BeEmpty();
        await result.Ids.Should().BeEmpty();
    }

    private const string GeneratedQuit = """
        // <auto-generated/>
        namespace KappaDuck.Khaos.Windowing
        {
            internal static unsafe partial class Native
            {
                [global::System.Runtime.CompilerServices.SkipLocalsInitAttribute]
                internal static partial void Quit()
                {
                    unsafe
                    {
                        __PInvoke();
                    }

                    [global::System.Runtime.InteropServices.DllImportAttribute("SDL3", EntryPoint = "SDL_Quit", ExactSpelling = true)]
                    static extern unsafe void __PInvoke();
                }
            }
        }
        """;
}
