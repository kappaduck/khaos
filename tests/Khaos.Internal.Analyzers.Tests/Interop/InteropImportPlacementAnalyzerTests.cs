using KappaDuck.Khaos.Internal.Analyzers.Interop;

namespace KappaDuck.Khaos.Internal.Analyzers.Tests.Interop;

internal sealed class InteropImportPlacementAnalyzerTests
{
    [Test]
    public async Task LibraryImportOutsideInteropShouldReportKHI009()
    {
        const string source = """
            using System.Runtime.InteropServices;

            namespace KappaDuck.Khaos.Windowing;

            internal static partial class Native
            {
                [LibraryImport("SDL3", EntryPoint = "SDL_Quit")]
                internal static partial void Quit();
            }
            """;

        AnalyzerResult result = await AnalyzerRunner<InteropImportPlacementAnalyzer>.RunAsync(source);

        await result.CompilationErrors.Should().BeEmpty();
        await result.Ids.Should().BeEqualTo("KHI009");
        await result.Reported.Should().BeEqualTo("Source0.cs(8,34): error KHI009: 'Quit' imports a native function outside Interop/SDL and Interop/Win32; move it to the area of its library");
    }

