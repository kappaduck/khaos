    [Test]
    public async Task MethodWithoutLibraryImportShouldReportNothing()
    {
        const string source = """
            namespace KappaDuck.Khaos.Interop.SDL;

            internal static class Errors
            {
                internal static void ThrowIfFailed(byte result)
                {
