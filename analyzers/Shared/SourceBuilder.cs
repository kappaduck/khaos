using System.Text;

namespace KappaDuck.Khaos.Analyzers.Shared;

internal sealed class SourceBuilder
{
    private const char NewLine = '\n';
    private const int IndentSize = 4;

    private readonly StringBuilder _builder = new();

    private int _indentation;

    internal SourceBuilder()
    {
        AppendLine("// <auto-generated/>");
        AppendLine("#nullable enable");
        AppendLine();
    }

    internal SourceBlock AppendBlock(string line) => AppendBlock(line, "}");

    internal SourceBlock AppendBlock(string line, string closing)
    {
        AppendLine(line);
        AppendLine("{");

        _indentation++;

        return new SourceBlock(this, closing);
    }

    internal SourceBuilder AppendLine(string line)
    {
        if (string.IsNullOrEmpty(line))
            return AppendLine();

        if (_indentation > 0)
            _builder.Append(' ', _indentation * IndentSize);

        _builder.Append(line).Append(NewLine);
        return this;
    }

    internal SourceBuilder AppendLine()
    {
        _builder.Append(NewLine);
        return this;
    }

    internal string Build() => _builder.ToString();

    private void Close(string closing)
    {
        _indentation--;
        AppendLine(closing);
    }

    internal readonly ref struct SourceBlock(SourceBuilder builder, string closing) : IDisposable
    {
        public void Dispose() => builder.Close(closing);
    }
}
