using System.Buffers;
using System.Runtime.CompilerServices;

namespace KappaDuck.Khaos.Analyzers.Shared;

internal sealed class CodeSourceBuilder : IDisposable
{
    private const int InitialCapacity = 1024;
    private const int IndentSize = 4;

    private char[]? _buffer;
    private int _length;
    private int _indentation;
    private bool _atLineStart = true;

    internal CodeSourceBuilder()
    {
        _buffer = ArrayPool<char>.Shared.Rent(InitialCapacity);

        AppendLine("// <auto-generated/>");
        AppendLine("#nullable enable");
        AppendLine();
    }

    public void Dispose()
    {
        if (_buffer is null)
            return;

        ArrayPool<char>.Shared.Return(_buffer);

        _buffer = null;
        _length = 0;
    }

    public override string ToString() => _buffer is null ? string.Empty : new(_buffer, 0, _length);

    internal CodeSourceBuilder Append(ReadOnlySpan<char> text)
    {
        Write(text);
        return this;
    }

    internal CodeSourceBuilder Append([InterpolatedStringHandlerArgument("")] ref LineHandler _) => this;

    internal CodeSourceBuilder AppendLine()
    {
        WriteNewLine();
        return this;
    }

    internal CodeSourceBuilder AppendLine(ReadOnlySpan<char> line)
    {
        Write(line);
        WriteNewLine();

        return this;
    }

    internal CodeSourceBuilder AppendLine([InterpolatedStringHandlerArgument("")] ref LineHandler _) => AppendLine();

    internal Block AppendBlock(ReadOnlySpan<char> line) => AppendBlock(line, "}");

    internal Block AppendBlock(ReadOnlySpan<char> line, string closing)
    {
        Write(line);
        return OpenBlock(closing);
    }

    internal Block AppendBlock([InterpolatedStringHandlerArgument("")] ref LineHandler _) => OpenBlock("}");

    internal Block AppendBlock([InterpolatedStringHandlerArgument("")] ref LineHandler _, string closing) => OpenBlock(closing);

    private void WriteNewLine()
    {
        char[] buffer = EnsureCapacity(1);
        buffer[_length++] = '\n';

        _atLineStart = true;
    }

    private void Write(ReadOnlySpan<char> text)
    {
        while (!text.IsEmpty)
        {
            int end = text.IndexOfAny('\r', '\n');

            if (end < 0)
            {
                WriteSegment(text);
                return;
            }

            WriteSegment(text[..end]);

            if (text[end] == '\n')
                WriteNewLine();

            text = text[(end + 1)..];
        }
    }

    private void Write(char value)
    {
        Span<char> one = stackalloc char[1];
        one[0] = value;

        Write(one);
    }

    private void Write(int value)
    {
        Span<char> digits = stackalloc char[11];

        int start = digits.Length;
        uint magnitude = value < 0 ? (uint)(-(long)value) : (uint)value;

        do
        {
            digits[--start] = (char)('0' + (magnitude % 10));
            magnitude /= 10;
        }
        while (magnitude != 0);

        if (value < 0)
            digits[--start] = '-';

        WriteSegment(digits[start..]);
    }

    private void WriteSegment(ReadOnlySpan<char> segment)
    {
        if (segment.IsEmpty)
            return;

        if (_atLineStart)
        {
            _atLineStart = false;
            WriteIndentation();
        }

        char[] buffer = EnsureCapacity(segment.Length);

        segment.CopyTo(buffer.AsSpan(_length));
        _length += segment.Length;
    }

    private void WriteIndentation()
    {
        int spaces = _indentation * IndentSize;

        char[] buffer = EnsureCapacity(spaces);

        buffer.AsSpan(_length, spaces).Fill(' ');
        _length += spaces;
    }

    private Block OpenBlock(string closing)
    {
        WriteNewLine();
        Write("{".AsSpan());
        WriteNewLine();

        _indentation++;
        return new Block(this, closing);
    }

    private void CloseBlock(string closing)
    {
        _indentation--;

        Write(closing.AsSpan());
        WriteNewLine();
    }

    private char[] EnsureCapacity(int additional)
    {
        char[] buffer = _buffer ?? throw new ObjectDisposedException(nameof(CodeSourceBuilder));

        if (_length + additional <= buffer.Length)
            return buffer;

        char[] larger = ArrayPool<char>.Shared.Rent(Math.Max(buffer.Length * 2, _length + additional));

        buffer.AsSpan(0, _length).CopyTo(larger);
        ArrayPool<char>.Shared.Return(buffer);

        return _buffer = larger;
    }

    [InterpolatedStringHandler]
    internal readonly ref struct LineHandler
    {
        private readonly CodeSourceBuilder _builder;

#pragma warning disable IDE0290 // Use primary constructor
        public LineHandler(int _, int _1, CodeSourceBuilder builder) => _builder = builder;
#pragma warning restore IDE0290 // Use primary constructor

        public readonly void AppendLiteral(string value) => _builder.Write(value.AsSpan());

        public readonly void AppendFormatted(string? value) => _builder.Write(value.AsSpan());

        public readonly void AppendFormatted(ReadOnlySpan<char> value) => _builder.Write(value);

        public readonly void AppendFormatted(char value) => _builder.Write(value);

        public readonly void AppendFormatted(int value) => _builder.Write(value);
    }

    internal readonly ref struct Block(CodeSourceBuilder builder, string closing) : IDisposable
    {
        public void Dispose() => builder.CloseBlock(closing);
    }
}
